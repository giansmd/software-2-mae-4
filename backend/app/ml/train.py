"""Train the ML surrogate models and compute their evaluation metrics.

Two heads share the same synthetic dataset generated by the engine:

  * a multi-output RandomForestRegressor that predicts the horizon variation
    percentage and the retained carbon, and
  * a RandomForestClassifier that predicts whether the scenario meets the
    +25% hypothesis.

Metrics and feature importances are stored alongside the fitted estimators so
the API can expose them and the UI can show how the model behaves.
"""
from __future__ import annotations

import datetime
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional, Union

import joblib
import numpy as np
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.metrics import (
    accuracy_score,
    mean_absolute_error,
    r2_score,
    roc_auc_score,
    root_mean_squared_error,
)
from sklearn.model_selection import cross_val_score, train_test_split

from app.ml.dataset import (
    DEFAULT_N_SAMPLES,
    DEFAULT_SEED,
    TrainingData,
    generate_dataset,
)

ARTIFACT_DIR = Path(__file__).resolve().parent / "artifacts"
ARTIFACT_PATH = ARTIFACT_DIR / "carbon_model.joblib"

MODEL_NAME = "RandomForest"
MODEL_VERSION = "1.0.0"
DATA_SOURCE = "synthetic (generado por el motor determinista)"
RANDOM_STATE = 42
N_ESTIMATORS = 150
TEST_SIZE = 0.2
CV_FOLDS = 3


@dataclass
class TrainedModel:
    regressor: RandomForestRegressor
    classifier: RandomForestClassifier
    metadata: dict[str, Any]


def train_model(
    n_samples: int = DEFAULT_N_SAMPLES,
    seed: int = DEFAULT_SEED,
    params: Optional[dict[str, float]] = None,
) -> TrainedModel:
    """Fit both surrogate heads and return them with their metrics."""
    data: TrainingData = generate_dataset(n_samples=n_samples, seed=seed, params=params)

    (
        X_train,
        X_test,
        yreg_train,
        yreg_test,
        ymeets_train,
        ymeets_test,
    ) = train_test_split(
        data.X,
        data.y_regression,
        data.y_meets,
        test_size=TEST_SIZE,
        random_state=RANDOM_STATE,
        shuffle=True,
    )

    regressor = RandomForestRegressor(
        n_estimators=N_ESTIMATORS,
        random_state=RANDOM_STATE,
        n_jobs=-1,
    )
    regressor.fit(X_train, yreg_train)
    reg_pred = regressor.predict(X_test)

    classifier = RandomForestClassifier(
        n_estimators=N_ESTIMATORS,
        random_state=RANDOM_STATE,
        n_jobs=-1,
        class_weight="balanced",
    )
    classifier.fit(X_train, ymeets_train)
    clf_pred = classifier.predict(X_test)

    cv_scores = cross_val_score(
        RandomForestRegressor(
            n_estimators=N_ESTIMATORS,
            random_state=RANDOM_STATE,
            n_jobs=-1,
        ),
        X_train,
        yreg_train,
        cv=CV_FOLDS,
        scoring="r2",
        n_jobs=-1,
    )

    importances = regressor.feature_importances_
    metadata: dict[str, Any] = {
        "algorithm": MODEL_NAME,
        "model_version": MODEL_VERSION,
        "data_source": DATA_SOURCE,
        "trained_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "n_samples": data.n_samples,
        "n_train": int(X_train.shape[0]),
        "n_test": int(X_test.shape[0]),
        "feature_names": list(data.feature_names),
        "feature_importances": {
            name: float(value)
            for name, value in zip(data.feature_names, importances.tolist())
        },
        "regression": {
            "r2_variation": float(r2_score(yreg_test[:, 0], reg_pred[:, 0])),
            "mae_variation": float(mean_absolute_error(yreg_test[:, 0], reg_pred[:, 0])),
            "rmse_variation": float(
                root_mean_squared_error(yreg_test[:, 0], reg_pred[:, 0])
            ),
            "r2_carbon": float(r2_score(yreg_test[:, 1], reg_pred[:, 1])),
            "mae_carbon": float(mean_absolute_error(yreg_test[:, 1], reg_pred[:, 1])),
            "rmse_carbon": float(
                root_mean_squared_error(yreg_test[:, 1], reg_pred[:, 1])
            ),
            "cv_r2_mean": float(np.mean(cv_scores)),
            "cv_r2_std": float(np.std(cv_scores)),
        },
        "classification": {
            "accuracy": float(accuracy_score(ymeets_test, clf_pred)),
            "roc_auc": float(
                roc_auc_score(ymeets_test, classifier.predict_proba(X_test)[:, 1])
            ),
        },
    }

    return TrainedModel(
        regressor=regressor,
        classifier=classifier,
        metadata=metadata,
    )


def save_model(model: TrainedModel, path: Union[str, Path] = ARTIFACT_PATH) -> Path:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump(
        {
            "regressor": model.regressor,
            "classifier": model.classifier,
            "metadata": model.metadata,
        },
        target,
    )
    return target


def load_model(path: Union[str, Path] = ARTIFACT_PATH) -> TrainedModel:
    payload = joblib.load(Path(path))
    return TrainedModel(
        regressor=payload["regressor"],
        classifier=payload["classifier"],
        metadata=payload["metadata"],
    )
